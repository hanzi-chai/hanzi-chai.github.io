/**
 * 用户在文本框里写「一串名字」时统一的分隔方式：**全角逗号、半角逗号、换行**。
 *
 * 三处共用：预置归并文本、手动指定字根、字根编码（含候选码）。
 * **只此一份**——改这里三处一起变。别在别处另写字符类，也别顺手加顿号/空格：
 * 顿号在根名里可能出现，空格在预置归并里是「码位」语法（`的 1=人 2`），都不安全。
 */
export const 分隔正则 = /[,\uFF0C\n]/;

/** 按 {@link 分隔正则} 拆开，逐个 trim，去空项。 */
export const 按分隔拆分 = (文本: string): string[] =>
  文本
    .split(分隔正则)
    .map((s) => s.trim())
    .filter(Boolean);
