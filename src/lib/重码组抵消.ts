/** 重码组变化的「抵消」清洗（手动分析页 / 加减根分析的展示层用）。
 *
 *  只做一件事：**整组抵消**。加根后若某个组解散、同时另一个组新生且成员完全一样，
 *  那是同一批字的码原地搬到另一个键上——组规模没变、分数一分没动，两条留着毫无信息
 *  （会显示成一对「－甲、乙」和「＋甲、乙」，看着像自相矛盾）。
 *
 *  **不做成员级抵消**（2026-10-23 试过又撤掉，别再捡回来）：
 *  把「A 组的离开」与「B 组的加入」里的同名项两边都划掉，表头（如 68→71）就和剩下的
 *  「＝68」对不上了——被划掉的名字两边都不出现，看着就像漏了数据。而且成员搬家恰恰是
 *  有用信息：它说明「这个字从拥挤组搬进了宽松组」，正是加根有没有效的地方。实测加「二」
 *  时这类成对搬家涉及近两万个名字，可读性靠折叠长名单（列前 10 个 + 总数）解决，不删信息。
 *
 *  复杂度：按成员集合签名配对，排序级，不做两两比较。
 */

export interface 阶重变化组 {
  基线词: string[];
  候选词: string[];
  基线: number;
  候选: number;
}

/** 成员集合的身份：与码位无关，只看「哪几个字挤在一起」 */
const 签名 = (词: string[]) => [...词].sort().join("\u0001");

export function 抵消组变化(变化组: 阶重变化组[]): 阶重变化组[] {
  if (变化组.length === 0) return 变化组;

  // 解散组（候选为空）与新生组（基线为空）各按成员集签名分桶
  const 解散池 = new Map<string, number[]>();
  const 新生池 = new Map<string, number[]>();
  变化组.forEach((g, i) => {
    const 是解散 = g.候选词.length === 0;
    const 是新生 = g.基线词.length === 0;
    if (!是解散 && !是新生) return; // 组还在、只是换了人：规模变化有信息，原样保留
    const 池 = 是解散 ? 解散池 : 新生池;
    const s = 签名(是解散 ? g.基线词 : g.候选词);
    const 列 = 池.get(s);
    if (列) 列.push(i);
    else 池.set(s, [i]);
  });

  // 同签名按数量配对：一对就是「原地搬家」，两条都不显示（可能有多对，逐对配）
  const 整组消 = new Uint8Array(变化组.length);
  解散池.forEach((解列, s) => {
    const 新列 = 新生池.get(s);
    if (!新列) return;
    for (let k = 0; k < Math.min(解列.length, 新列.length); k++) {
      整组消[解列[k]!] = 1;
      整组消[新列[k]!] = 1;
    }
  });

  const 输出: 阶重变化组[] = [];
  变化组.forEach((g, i) => {
    if (!整组消[i]) 输出.push(g);
  });
  return 输出;
}
