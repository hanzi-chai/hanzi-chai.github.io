/**
 * 标准装配——全站唯一的「方案装配」实现（2026-10-03 起）。
 *
 * 网页手动分析（cache.ts 原子）、智能选根核心、CLI 评分脚本全部经由本模块构建
 * 「映射无关」的装配上下文（字库/词典/拼音分析/名称映射/自定义分析，均与 form.mapping 无关）；
 * 映射相关步骤（决策、字形分析、组装、增量评分）由各消费方自行实现，但只吃本模块的产物。
 *
 * 背景：此前三处各自内联同一配方，先后产生过六类静默口径漂移（均只对特定方案形态显形）：
 *  ① 计算拼音分析与元素映射 被多次调用——每次调用都 new 拼音元素，对象身份断裂后
 *     取码器查不到字音元素键长，音形方案的拼音码位被整体丢弃；
 *  ② analysis.customize / dynamic_customize 没传进字形分析（自定义拆分字被默认规则重拆）；
 *  ③ 字形来源缺省 [] 而站点是 ["G"]（部分字主字形不同）；
 *  ④ 字集缺省不过滤而站点是 "general"=通用规范字表（字集外字混进统计）；
 *  ⑤ 组装/名称映射的分类器用默认分类器而站点合并 analysis.classifier（笔画系方案取码不同）；
 *  ⑥ 总分逐表舍入后累加 vs 未舍入累加（显示层，见 RootAdditionAnalyzer 总初态）。
 * 改动本文件的口径前，先用 大一统对账/基线.json 的四方案三面数据回归。
 */
