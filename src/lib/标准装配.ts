/** 装配输入：一份方案跑分所需的全部「映射无关」原料。数据范围（内置字库、用户字库、
 *  用户词典、IndexedDB 自定义元素）由调用方决定，本模块只管配方。 */
export interface 装配输入 {
  原始字库: 原始字库;
  原始词典: 原始词典;
  字形自定义: 兼容字形自定义;
  变换器列表: 变换器[];
  字形来源列表: 源标签[];
  字集指示: 字集指示;
  拼写运算查找表: Map<string, 拼写运算>;
  分类器自定义: Record<string, number>;
  自定义拆分: Record<string, string[]>;
  动态自定义拆分: Record<string, string[][]>;
  /** 站点传 IndexedDB「自定义分析」条目（配合 encoder 自定义源），CLI 传 {} */
  自定义元素集合: Record<string, 自定义分析>;
  /** 名称映射构建时的字符顺序。两序对分数无影响（已验证），站点用笔顺保持现状，CLI 用字库序。 */
  字符排序?: "笔顺" | "字库序";
}

export interface 标准上下文 {
  原始字库: 原始字库;
  词典: 词典;
  过滤词典: 词典;
  汉字集合: Set<字符>;
  /** 字库.确定 的产物；失败时为 undefined 并带 字库错误（各消费方按原语义自行降级） */
  字库?: 字库;
  字库错误?: Error;
  拼音元素映射: Map<string, any[]>;
  拼音分析映射: 拼音分析映射;
  拼音分析: 拼音分析结果;
  分类器: 分类器;
  /** 校验自定义映射 的两个产物：分析映射是逐字自定义元素位（组装配置用），元素映射是类别→元素列表（名称映射用） */
  自定义元素分析映射: Map<any, any>;
  自定义元素映射: Map<string, any[]>;
  /** 字库确定失败时为 undefined */
  名称映射?: Map<string, 元素>;
  自定义分析映射: Map<any, any[]>;
  动态自定义分析映射: Map<any, any[][]>;
}

export function 构建标准上下文(输入: 装配输入): 标准上下文 {
  // 1) 词典链：校验 → 字集过滤 → 汉字集合（字集缺省语义由调用方给足，见 装配输入自配置）
  const 词典 = 输入.原始字库.校验词典(输入.原始词典);
  const 过滤词典 = 输入.原始字库.过滤词典(词典, 输入.字集指示);
  const 汉字集合 = 输入.原始字库.获取汉字集合(过滤词典);
  // 2) 拼音：计算拼音分析与元素映射 只许调用一次（每次调用都 new 拼音元素，
  //    名称映射/决策与拼音分析必须共享同一批对象，否则字音码位被取码器整体丢弃）
  const { 拼音元素映射, 拼音分析映射 } = 计算拼音分析与元素映射(词典, 输入.拼写运算查找表);
  const 拼音分析 = 分析拼音(拼音分析映射, 过滤词典);
  // 3) 分类器与自定义元素
  const 分类器 = 合并分类器(输入.分类器自定义);
  const 校验自定义 = 输入.原始字库.校验自定义映射(输入.自定义元素集合);
  const 自定义元素映射 = 校验自定义.自定义元素映射;
  // 4) 字库（可能失败：字形自定义引用缺失字符等；失败不连坐词典/拼音层）
  const 字库结果 = 输入.原始字库.确定(标准化自定义(输入.字形自定义), 输入.变换器列表, 输入.字形来源列表);
  let 字库: 字库 | undefined;
  let 字库错误: Error | undefined;
  let 名称映射: Map<string, 元素> | undefined;
  let 自定义分析映射: Map<any, any[]> = new Map();
  let 动态自定义分析映射: Map<any, any[][]> = new Map();
  if (字库结果.ok) {
    字库 = 字库结果.value;
    const 全部字符 = [...字库].map(({ 字符 }) => 字符);
    const 字符列表 =
      输入.字符排序 === "笔顺"
        ? 排序按笔顺(字库, 全部字符)
        : 全部字符;
    名称映射 = 计算全部合法元素与元素映射(字符列表, 分类器, 拼音元素映射, 自定义元素映射).名称映射;
    const 自定义分析 = 构建强类型自定义分析(
      字库,
      输入.原始字库,
      名称映射,
      输入.自定义拆分,
      输入.动态自定义拆分,
    );
    自定义分析映射 = 自定义分析.自定义分析映射;
    动态自定义分析映射 = 自定义分析.动态自定义分析映射;
  } else {
    字库错误 =
      字库结果.error instanceof Error ? 字库结果.error : new Error(String(字库结果.error));
  }
  return {
    原始字库: 输入.原始字库,
    词典,
    过滤词典,
    汉字集合,
    字库,
    字库错误,
    拼音元素映射,
    拼音分析映射,
    拼音分析,
    分类器,
    自定义元素分析映射: 校验自定义.自定义分析映射,
    自定义元素映射,
    名称映射,
    自定义分析映射,
    动态自定义分析映射,
  };
}

/** 从完整配置推导 装配输入（CLI 脚本与智能选根核心用；站点的数据范围特殊，自行拼 装配输入）。
 *  口径锚点：字形来源缺省 ["G"]、字集缺省 "general"——与站点对应原子的 valueOr 一致。 */
export function 装配输入自配置(
  配置: any,
  原始词典: 原始词典,
  原始字库: 原始字库,
  自定义元素集合: Record<string, 自定义分析> = {},
): 装配输入 {
  return {
    原始字库,
    原始词典,
    字形自定义: 配置.data?.glyph_customization ?? {},
    变换器列表: 配置.data?.transformers ?? [],
    字形来源列表: (配置.data?.glyph_sources ?? ["G"]) as 源标签[],
    字集指示: (配置.data?.character_set ?? "general") as 字集指示,
    拼写运算查找表: 合并拼写运算(配置.algebra),
    分类器自定义: 配置.analysis?.classifier ?? {},
    自定义拆分: 配置.analysis?.customize ?? {},
    动态自定义拆分: 配置.analysis?.dynamic_customize ?? {},
    自定义元素集合,
  };
}

/** 与 cache.ts 如按笔顺排序字符原子 同款排序（首字形笔画数升序） */
function 排序按笔顺(字库: 字库, 全部字符: 字符[]): 字符[] {
  const 笔顺映射 = new Map<字符, string[]>();
  for (const { 字符, 字形列表 } of 字库) {
    笔顺映射.set(
      字符,
      字形列表.map((g) => g.获取笔画序列(默认分类器).join("")),
    );
  }
  return sortByBy(全部字符, (c) => 笔顺映射.get(c)?.[0]?.length ?? 0);
}

function sortByBy<T>(列表: T[], 权: (x: T) => number): T[] {
  return [...列表].sort((a, b) => 权(a) - 权(b));
}

/** 归并展开的唯一实现：沿决策把归并/引用码位替换到最终形态（网页「带归并」同款）。
 *  决策里没有安排的元素原样保留；引用到字符串安排时停在当前码位。 */
export function 展开归并码位(
  码位: 强类型元素位或编码,
  决策: 强类型决策,
): 强类型元素位或编码 {
  if (typeof 码位 === "string") return 码位;
  let 当前 = 码位;
  for (let i = 0; i < 100; i++) {
    const 安排 = 决策.get(当前.element);
    if (!安排) break;
    if (是强类型归并(安排)) {
      当前 = { ...当前, element: 安排.element };
    } else if (Array.isArray(安排)) {
      const 引用 = 安排[当前.index ?? 0];
      if (引用 === undefined || typeof 引用 === "string") break;
      当前 = 引用;
    } else break;
  }
  return 当前;
}
